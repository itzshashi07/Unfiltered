#!/usr/bin/env python3
"""Writes docs/CONTENT_INDEX.md: a compact English index of everything in the curriculum."""
import glob, json, os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
C = os.path.join(ROOT, "assets", "content")


def load(kind, d):
    p = os.path.join(C, kind, f"{d}.json")
    return json.load(open(p, encoding="utf-8")) if os.path.exists(p) else []


t = lambda item: ",".join(item.get("tracks", []))
out = ["# Content index (English, generated by tools/content_index.py)", "",
       "Tracks: A = ages 5-8, B = 9-12, C = 13-15, D = 16-17, E = 18+. `l` lesson, `f` FAQ, `m` myth card, `s` scenario.", ""]
for d in json.load(open(os.path.join(C, "domains.json"), encoding="utf-8")):
    did = d["id"]
    out += [f"## {did} — {d['title']['en']}  (allowed tracks: {','.join(d['tracks'])})", ""]
    out.append("Lessons:")
    for l in load("lessons", did):
        out.append(f"- {l['id']} [{t(l)}] {l['title']['en']} — {l['subtitle']['en']}")
        out.append("    sections: " + " | ".join(s["h"]["en"] for s in l["sections"]))
        out.append(f"    myth addressed: {l['myth']['claim']['en']}")
    out.append("FAQs:")
    for f in load("faqs", did):
        out.append(f"- {f['id']} [{t(f)}]{' (urgent)' if f.get('urgent') else ''} {f['q']['en']}")
    out.append("Myth cards:")
    for m in load("myths", did):
        out.append(f"- {m['id']} [{t(m)}] ({m['verdict']}) {m['claim']['en']}")
    sc = load("scenarios", did)
    if sc:
        out.append("Scenarios:")
        for s in sc:
            out.append(f"- {s['id']} [{t(s)}] ({s['module']}) {s['title']['en']} — {s['intro']['en']}")
    out.append("Glossary: " + "; ".join(f"{g['title']['en']} [{t(g)}]: " + ", ".join(x["term"]["en"] for x in g["terms"]) for g in load("glossary", did)))
    out.append(f"Quiz bank questions: {len(load('quiz', did))}")
    out.append("")
labs = json.load(open(os.path.join(C, "extras", "labs.json"), encoding="utf-8"))
social = json.load(open(os.path.join(C, "extras", "social.json"), encoding="utf-8"))
out += ["## Labs and support data", "",
        "Body Lab parts: " + ", ".join(f"{b['id']} [{t(b)}]" for b in labs["body_parts"]),
        "Puberty Lab changes: " + ", ".join(p["name"]["en"] for p in labs["puberty_changes"]),
        "Protection Lab methods: " + ", ".join(m["name"]["en"] for m in labs["methods"]),
        "Prevention cards: " + ", ".join(f"{p['title']['en']} [{t(p)}]" for p in labs["prevention_cards"]),
        "STI Challenge: " + ", ".join(s["name"]["en"] for s in labs["sti_match"]),
        "Safety Center guides: " + " | ".join(f"{g['title']['en']} [{t(g)}]" for g in social["safety_guidance"]),
        "Parent guide: " + " | ".join(g["title"]["en"] for g in social["parent_guide"]),
        "Support circle: " + " | ".join(f"{s['title']['en']} [{t(s)}]" for s in social["support_circle"]),
        f"Daily facts: {len(social['daily_facts'])}; relationship signals: {len(social['signals'])}; digital challenge items: {len(social['digital_challenge'])}",
        ""]
open(os.path.join(ROOT, "docs", "CONTENT_INDEX.md"), "w", encoding="utf-8").write("\n".join(out))
print("wrote docs/CONTENT_INDEX.md", len(out), "lines")
