#!/usr/bin/env python3
"""Builds docs/COVERAGE.md and docs/curriculum_matrix.json from the content packs (real counts)."""
import glob, json, os
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
C = os.path.join(ROOT, "assets", "content")
def load(kind):
    out = []
    for f in sorted(glob.glob(os.path.join(C, kind, "*.json"))):
        out += json.load(open(f, encoding="utf-8"))
    return out
domains = json.load(open(os.path.join(C, "domains.json"), encoding="utf-8"))
lessons, faqs, myths, quiz, gloss, scen = (load(k) for k in ("lessons", "faqs", "myths", "quiz", "glossary", "scenarios"))
UNESCO = ["Relationships", "Values, Rights, Culture and Sexuality", "Understanding Gender", "Violence and Staying Safe",
          "Skills for Health and Well-being", "The Human Body and Development", "Sexuality and Sexual Behaviour",
          "Sexual and Reproductive Health"]
T = "ABCDE"; AGES = {"A": "5–8", "B": "9–12", "C": "13–15", "D": "16–17", "E": "18+"}
n = lambda items, d: sum(1 for i in items if i["domain"] == d)
matrix = {"generated_from": "assets/content", "unesco_concepts": {str(i + 1): u for i, u in enumerate(UNESCO)},
          "tracks": AGES, "domains": [], "lessons": []}
md = ["# Curriculum coverage report", "",
      "Generated by `python3 tools/coverage_report.py` from the content packs. These are real counts, not targets.", "",
      "## Totals", "", "| Item | Target in brief | Actual |", "|---|---|---|",
      f"| Lessons | 96 | **{len(lessons)}** |", f"| FAQ entries | 200 | **{len(faqs)}** |",
      f"| Quiz questions | 200 | **{len(quiz) + sum(len(l['quiz']) for l in lessons)}** ({sum(len(l['quiz']) for l in lessons)} in lessons + {len(quiz)} in the bank) |",
      f"| Myth-versus-fact cards | 120 | **{len(myths)}** |", f"| Branching scenarios | 24 | **{len(scen)}** |",
      f"| Glossary sets | 30 | **{len(gloss)}** ({sum(len(g['terms']) for g in gloss)} terms) |", "",
      "Every item exists in English, Hindi and Hinglish. Review status of every item: **pending expert review**.", "",
      "## Lessons per domain and age track", "",
      "| # | Domain | UNESCO concepts | " + " | ".join(AGES[t] for t in T) + " | Lessons | FAQs | Myths | Quiz | Scenarios |",
      "|---|---|---|" + "---|" * 10]
for d in domains:
    ls = [l for l in lessons if l["domain"] == d["id"]]
    per = {t: sum(1 for l in ls if t in l["tracks"]) for t in T}
    q = n(quiz, d["id"]) + sum(len(l["quiz"]) for l in ls)
    md.append(f"| {d['id'][1:]} | {d['title']['en']} | {', '.join(map(str, d['unesco']))} | " +
              " | ".join(str(per[t]) if per[t] else "–" for t in T) +
              f" | {len(ls)} | {n(faqs, d['id'])} | {n(myths, d['id'])} | {q} | {n(scen, d['id']) or '–'} |")
    matrix["domains"].append({"id": d["id"], "title": d["title"], "unesco": d["unesco"], "allowed_tracks": d["tracks"],
                              "lessons_per_track": per, "faqs": n(faqs, d["id"]), "myths": n(myths, d["id"]), "quiz": q,
                              "scenarios": n(scen, d["id"])})
md += ["", "A dash means the domain is deliberately not taught at that age.", "", "## Items visible to each track", "",
       "| Track | Ages | Lessons | FAQs | Myth cards | Scenarios |", "|---|---|---|---|---|---|"]
for t in T:
    md.append(f"| {t} | {AGES[t]} | {sum(1 for l in lessons if t in l['tracks'])} | {sum(1 for f in faqs if t in f['tracks'])} | "
              f"{sum(1 for m in myths if t in m['tracks'])} | {sum(1 for s in scen if t in s['tracks'])} |")
md += ["", "## UNESCO key concepts", "", "| # | Concept | Lessons mapped |", "|---|---|---|"]
for i, u in enumerate(UNESCO, 1):
    md.append(f"| {i} | {u} | {sum(1 for l in lessons if i in l['unesco'])} |")
md += ["", "The mapping is this project's own. It is not a certification or endorsement by UNESCO.", "", "## Lesson index", "",
       "| ID | Ages | Min | Level | Title | Lab |", "|---|---|---|---|---|---|"]
for l in lessons:
    md.append(f"| {l['id']} | {', '.join(AGES[t] for t in l['tracks'])} | {l['minutes']} | {l['difficulty']} | {l['title']['en']} | {l['interactive'] or '–'} |")
    matrix["lessons"].append({k: l[k] for k in ("id", "domain", "tracks", "difficulty", "minutes", "unesco", "prereqs", "interactive", "refs", "sensitive", "review", "revised")} |
                             {"title": l["title"], "objectives": l["objectives"]})
open(os.path.join(ROOT, "docs", "COVERAGE.md"), "w", encoding="utf-8").write("\n".join(md) + "\n")
json.dump(matrix, open(os.path.join(ROOT, "docs", "curriculum_matrix.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
print("wrote docs/COVERAGE.md and docs/curriculum_matrix.json:", len(lessons), "lessons")
